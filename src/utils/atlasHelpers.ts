// 获取城市诗意笺注
export const getCityEpithet = (code: string, cityName?: string): string => {
  if (CITY_EPITHETS[code]) return CITY_EPITHETS[code]
  return `${cityName?.replace(/市|特别行政区/g, '') || '山川'} · 岁月留步之城`
}

// 格式化到访次数为复古中文印章计数
export const formatVisitStampCount = (count: number): string => {
  const digits = ['零', '壹', '贰', '叁', '肆', '伍', '陆', '柒', '捌', '玖', '拾']
  if (count === 1) return '初次踏足'
  if (count <= 10) return `${digits[count]}次留步`
  return `${count}次留步`
}
